/// Where `{account_id}` / `{zone_id}` come from.
enum SpecScope { account, zone, user }

/// An extra operation on an item (or on the whole list when used in
/// [ResourceSpec.listActions]), e.g. "rotate secret" or "purge queue".
class ItemAction {
  const ItemAction({
    required this.label,
    required this.icon,
    required this.method,
    required this.path,
    this.confirm = false,
    this.danger = false,
    this.showResult = true,
    this.withBody = false,
    this.bodyBuilder,
  });

  final L10nText label;
  final IconData icon;
  final String method;

  /// Template; `{id}` is the item id, `{parent}` the parent id.
  final String path;
  final bool confirm;
  final bool danger;
  final bool showResult;

  /// Ask for a body using the operation's schema.
  final bool withBody;

  /// Fixed body computed from the item.
  final Object? Function(Map<String, dynamic> item)? bodyBuilder;
}

/// Declarative description of a REST collection: list, view, create,
/// update and delete are rendered by the generic resource pages, with
/// forms generated from the API catalog.
class ResourceSpec {
  const ResourceSpec({
    required this.id,
    required this.title,
    required this.group,
    required this.icon,
    required this.listPath,
    this.scope = SpecScope.account,
    this.itemPath,
    this.idField = 'id',
    this.titleFields = const ['name', 'title', 'id'],
    this.subtitleFields = const [],
    this.statusField,
    this.canCreate = true,
    this.createPath,
    this.updateMethod,
    this.canDelete = true,
    this.paginate = true,
    this.perPage = 50,
    this.listQuery,
    this.keywords = const [],
    this.description,
    this.children = const [],
    this.actions = const [],
    this.listActions = const [],
    this.dangerNameField,
    this.hiddenCreateFields = const {},
  });

  final String id;
  final L10nText title;
  final L10nText group;
  final IconData icon;
  final SpecScope scope;

  /// List endpoint template, e.g. `/accounts/{account_id}/queues`.
  /// For child specs `{parent}` is the parent item's id.
  final String listPath;

  /// Item endpoint template using `{id}`. Defaults to `$listPath/{id}`.
  final String? itemPath;
  final String idField;
  final List<String> titleFields;
  final List<String> subtitleFields;
  final String? statusField;
  final bool canCreate;
  final String? createPath;

  /// `PUT`, `PATCH` or `null` when items cannot be edited.
  final String? updateMethod;
  final bool canDelete;
  final bool paginate;
  final int perPage;
  final Map<String, dynamic>? listQuery;
  final List<String> keywords;
  final L10nText? description;
  final List<ResourceSpec> children;
  final List<ItemAction> actions;
  final List<ItemAction> listActions;

  /// Field the user must type to confirm deletion (defaults to title).
  final String? dangerNameField;
  final Set<String> hiddenCreateFields;

  String get resolvedItemPath => itemPath ?? '$listPath/{id}';
  bool get hasItemPath => itemPath != null || canDelete || updateMethod != null;
}

/// A single JSON document (settings object) that can be viewed and
/// replaced/patched, e.g. Gateway configuration.
class DocumentSpec {
  const DocumentSpec({
    required this.id,
    required this.title,
    required this.group,
    required this.icon,
    required this.path,
    this.scope = SpecScope.account,
    this.method,
    this.description,
    this.keywords = const [],
  });

  final String id;
  final L10nText title;
  final L10nText group;
  final IconData icon;
  final String path;
  final SpecScope scope;

  /// `PUT` / `PATCH`, or `null` for read-only documents.
  final String? method;
  final L10nText? description;
  final List<String> keywords;
}

